#!/usr/bin/env python3
"""Quantum win rate against EACH classical baseline individually.

Part II reports the two endpoints of the baseline choice -- 17% against logistic regression,
1% against best-of-six. The ladder between them is more informative than either, and is
already implicit in the results files: logistic regression is a large outlier from the
next-weakest single model, so even a sweep that never computed best-of-six would have killed
the headline.

Sources: experiments/results/classical_baselines.json (per dataset, seed, model test error)
and experiments/results/phase_b.jsonl (per cell quantum test error). Emits JSON and a LaTeX
table; nothing here is transcribed by hand.
"""
from __future__ import annotations
import json, collections
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS = ["lr", "knn", "svm", "mlp", "gbm", "rf"]
PRETTY = {"lr": "logistic regression", "knn": "$k$-NN", "svm": "SVC-RBF",
          "mlp": "MLP", "gbm": "HistGBM", "rf": "random forest"}

CB = json.load(open(ROOT / "experiments/results/classical_baselines.json"))
Q = [json.loads(l) for l in open(ROOT / "experiments/results/phase_b.jsonl") if l.strip()]

def rates(cells):
    wins, tot = collections.Counter(), collections.Counter()
    for r in cells:
        d, s, aq = r["dataset_id"], str(r["seed"]), r["epsilon_test_q"]
        if d not in CB or s not in CB[d]:
            continue
        errs = {m: CB[d][s][m]["test"] for m in MODELS if m in CB[d][s]}
        if not errs:
            continue
        for m, e in errs.items():
            tot[m] += 1
            wins[m] += aq < e
        tot["best"] += 1;  wins["best"] += aq < min(errs.values())
        tot["worst"] += 1; wins["worst"] += aq < max(errs.values())
    return {k: (wins[k], tot[k], 100.0 * wins[k] / tot[k] if tot[k] else float("nan"))
            for k in list(MODELS) + ["best", "worst"]}

full = rates(Q)
parity = rates([r for r in Q if r["dataset_id"].startswith("synth-parity")])
out = {"full_suite": full, "parity_family": parity,
       "note": "win = quantum test error strictly below that baseline's test error, same (dataset, seed)"}
json.dump(out, open(ROOT / "analysis/baseline_ladder.json", "w"), indent=1)

order = sorted(MODELS, key=lambda m: -full[m][2])
rows = "\n".join(
    "%s & %.1f\\%% & %.1f\\%% \\\\" % (PRETTY[m], full[m][2], parity[m][2]) for m in order)
tex = r"""% generated by analysis/baseline_ladder.py -- do not edit by hand
\begin{table}[tbp]
\centering
\small
\caption{Quantum win rate against each classical baseline taken \emph{individually}, over the
same $8{,}100$ Phase~B cells. A win is a strictly lower held-out error at matched
$(\text{dataset},\text{seed})$. Logistic regression is not merely the weakest of the six --- it
is a factor of three below the next weakest, and every other single model already places the
win rate under $6\%$. The headline therefore does not require taking the best of the set to
disappear; any of the other five would have removed it.}
\label{tab:baseline-ladder}
\begin{tabular}{@{}lrr@{}}
\toprule
baseline & full suite & parity family \\
\midrule
""" + rows + r"""
\midrule
worst of six & %.1f\%% & %.1f\%% \\
\textbf{best of six} & \textbf{%.1f\%%} & \textbf{%.1f\%%} \\
\bottomrule
\end{tabular}
\end{table}
""" % (full["worst"][2], parity["worst"][2], full["best"][2], parity["best"][2])
(ROOT / "paper2/tables").mkdir(parents=True, exist_ok=True)
open(ROOT / "paper2/tables/baseline_ladder.tex", "w").write(tex)

print("%-22s %12s %14s" % ("baseline", "full suite", "parity family"))
print("-" * 50)
for m in order:
    print("  %-20s %10.1f%% %13.1f%%" % (PRETTY[m], full[m][2], parity[m][2]))
print("-" * 50)
print("  %-20s %10.1f%% %13.1f%%" % ("worst of six", full["worst"][2], parity["worst"][2]))
print("  %-20s %10.1f%% %13.1f%%" % ("best of six", full["best"][2], parity["best"][2]))
print("\nwrote analysis/baseline_ladder.json and paper2/tables/baseline_ladder.tex")
