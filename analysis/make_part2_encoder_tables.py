"""Tables for Part II's encoder section, folded in from the decoding-window work."""
import json, os, numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES  = os.path.join(ROOT, "experiments", "results")
OUT  = os.path.join(ROOT, "paper2", "tables")
cr = json.load(open(os.path.join(RES, "reducer_condition_r.json")))
ds = json.load(open(os.path.join(RES, "reducer_datasets.json")))
hw = json.load(open(os.path.join(RES, "headroom_vs_width.json")))

# ---- cost of running a reducer coherently ----
T = [r"% generated by analysis/make_part2_encoder_tables.py -- do not edit by hand",
     r"\begin{table}[!htbp]", r"\centering\footnotesize", r"\setlength{\tabcolsep}{3pt}",
     r"""\caption{\textbf{What a dimensionality reduction costs to run on a superposition.} Upper
block: garbage of the reduction map, enumerated exactly over the whole quantised input cube at
matched $(p,d,b)$, so both reducers discard the same $p-d$ dimensions. Feature selection attains
the floor $(p-d)b$ \emph{exactly} in every row --- it drops whole registers and touches nothing
else --- while an orthonormal rotation must round, and rounding destroys more than it was asked to.
The gap is small in the Landauer average and $2.1$--$2.3\times$ in the worst-case preimage, which
is what an ancilla count pays for. Lower block: reversible circuit resources at $b=8$. Selection is
a relabelling of registers; a rotation accumulates $p$ constant-multiplies per output, needing
$2b+\lceil\log_2 p\rceil$ bits of accumulator.}""",
     r"\label{tab:reducercost}",
     r"\begin{tabular}{@{}l c c c c@{}}", r"\toprule",
     r"$(p,d,b)$ & floor & selection & rotation & max preim. \\", r"\midrule"]
for r in cr["part1"]:
    T.append(f"$({r['p']},{r['d']},{r['b']})$ & {r['predicted']} & "
             f"\\textbf{{{r['sel_bits']:.3f}}} & {r['rot_bits']:.3f} & {r['rot_max']:.0f} \\\\")
T += [r"\addlinespace", r"\midrule",
      r"dataset ($d{=}4$) & sel. & rot.\ anc. & garbage & overhead \\", r"\midrule"]
for r in cr["part2"]:
    if r["d"] != 4: continue
    T.append(f"{r['dataset'].split(' p=')[0]} & \\textbf{{0}} & {r['rot_anc']} & {r['rot_garbage']} & "
             f"${r['overhead']:.1f}\\times$ \\\\")
T += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
open(os.path.join(OUT, "reducer_cost.tex"), "w").write("\n".join(T) + "\n")

# ---- headroom vs width ----
H = [r"% generated by analysis/make_part2_encoder_tables.py -- do not edit by hand",
     r"\begin{table}[!htbp]", r"\centering\footnotesize", r"\setlength{\tabcolsep}{4pt}",
     r"""\caption{\textbf{Headroom after reduction, and the controls that make the zeros
readable.} \emph{Headroom} is gradient boosting minus a linear probe on the same reduced features,
the accuracy a non-linear model --- quantum or otherwise --- could still be demonstrating something
on. The maximum is taken over widths $d$ from $2$ to the full feature count, so these are not
small-$d$ artefacts. On the benchmark datasets it is indistinguishable from zero at \emph{every}
width, including no reduction at all. The two positive controls are what license reading that as a
property of the data: the certified $[16,4,5]$ code data, whose label is a $\mathrm{GF}(2)$
combination no linear-over-$\mathbb{R}$ model can see, and parity-8. \textbf{Parity-8 also shows the
metric's limit} --- its headroom reads $0.004$ because gradient boosting fails on parity too, so
headroom near zero means \emph{either} no exploitable structure \emph{or} structure beyond the
non-linear baseline as well.}""",
     r"\label{tab:headroom}",
     r"\begin{tabular}{@{}l l c c c@{}}", r"\toprule",
     r"dataset & kind & $p$ & max headroom & $d^{*}$ \\", r"\midrule"]
for r in hw["summary"]:
    kind = r["kind"].replace("POSITIVE CONTROL", r"\textbf{control}")
    ds_ = str(r["d_star"]) if r["d_star"] else "---"
    bold = r"\textbf{" + f"{r['max_headroom']:+.3f}" + "}" if r["kind"] != "benchmark" else f"{r['max_headroom']:+.3f}"
    H.append(f"{r['dataset'].replace('certified[16,4]','certified $[16,4,5]$')} & {kind} & "
             f"{r['p']} & {bold} & {ds_} \\\\")
H += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
open(os.path.join(OUT, "headroom.tex"), "w").write("\n".join(H) + "\n")
sel=[r for r in ds if r["reducer"]=="selection"]; pca=[r for r in ds if r["reducer"]=="PCA"]
print(f"wrote reducer_cost.tex, headroom.tex")
print(f"  selection: nl {np.mean([r['nl'] for r in sel]):.3f} headroom {np.mean([r['headroom'] for r in sel]):+.3f}")
print(f"  PCA:       nl {np.mean([r['nl'] for r in pca]):.3f} headroom {np.mean([r['headroom'] for r in pca]):+.3f}")
